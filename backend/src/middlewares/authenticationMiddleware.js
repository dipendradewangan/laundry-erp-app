/**
 * ============================================================
 * Laundry ERP - Authentication Middleware
 * ============================================================
 *
 * File:
 * src/middlewares/authenticationMiddleware.js
 *
 * Purpose:
 * --------
 * Protect APIs that require an authenticated user.
 *
 * Responsibilities:
 * -----------------
 * 1. Read the access token from the Authorization header.
 * 2. Verify the JWT signature and expiry.
 * 3. Validate the JWT issuer and audience.
 * 4. Verify that the authentication session is active.
 * 5. Verify that the user is active and login is enabled.
 * 6. Attach verified user information to req.user.
 *
 * Expected header:
 * ----------------
 * Authorization: Bearer <access_token>
 *
 * Security:
 * ---------
 * - Never trust user IDs supplied in request bodies.
 * - Never accept refresh tokens as access tokens.
 * - Never trust session IDs without validating the database.
 * ============================================================
 */

import jwt from "jsonwebtoken";

import { findActiveSessionBySessionId } from "../repositories/auth/sessionRepository.js";

import { findUserById } from "../repositories/auth/userRepository.js";

import { AppError } from "../utils/errors/AppError.js";

import { ERROR_CODES } from "../utils/errors/errorCodes.js";


/**
 * JWT configuration.
 *
 * These values must match the configuration used when
 * the access token is generated by authSessionService.js.
 */
const JWT_ISSUER = "laundry-erp";
const JWT_AUDIENCE = "laundry-erp-api";


/**
 * Create a standardized authentication error.
 *
 * @param {string} message
 * @returns {AppError}
 */
const createAuthenticationError = (message) => {
    return new AppError(
        message,
        401,
        ERROR_CODES.UNAUTHORIZED
    );
};


/**
 * ============================================================
 * Authentication Middleware
 * ============================================================
 *
 * Usage:
 *
 * router.get(
 *     "/protected",
 *     authenticationMiddleware,
 *     controller
 * );
 */
export const authenticationMiddleware = async (
    req,
    res,
    next
) => {
    try {

        /**
         * STEP 1:
         * Read the Authorization header.
         */
        const authorizationHeader = req.headers.authorization;

        if (
            typeof authorizationHeader !== "string" ||
            !authorizationHeader.trim()
        ) {
            throw createAuthenticationError(
                "Authentication token is required."
            );
        }


        /**
         * STEP 2:
         * Extract the Bearer access token.
         */
        const bearerMatch = authorizationHeader.match(
            /^Bearer\s+(\S+)$/i
        );

        if (!bearerMatch) {
            throw createAuthenticationError(
                "Authorization header must use Bearer token format."
            );
        }

        const accessToken = bearerMatch[1];


        /**
         * STEP 3:
         * Verify the JWT signature and expiry.
         *
         * Do not accept tokens with an unexpected algorithm.
         */
        const jwtSecret = process.env.JWT_ACCESS_SECRET;

        if (
            typeof jwtSecret !== "string" ||
            !jwtSecret.trim()
        ) {
            throw new AppError(
                "Authentication configuration is unavailable.",
                500,
                ERROR_CODES.INTERNAL_SERVER_ERROR
            );
        }

        let decoded;

        try {
            decoded = jwt.verify(
                accessToken,
                jwtSecret,
                {
                    algorithms: ["HS256"],
                    issuer: JWT_ISSUER,
                    audience: JWT_AUDIENCE,
                }
            );
        } catch (error) {

            if (
                error.name === "TokenExpiredError" ||
                error.name === "JsonWebTokenError" ||
                error.name === "NotBeforeError"
            ) {
                throw createAuthenticationError(
                    "Access token is invalid or expired."
                );
            }

            throw error;
        }


        /**
         * STEP 4:
         * Validate the required JWT claims.
         *
         * sub = user ID
         * sid = authentication session ID
         */
        if (
            !decoded ||
            typeof decoded !== "object" ||
            typeof decoded.sub !== "string" ||
            typeof decoded.sid !== "string"
        ) {
            throw createAuthenticationError(
                "Access token claims are invalid."
            );
        }


        /**
         * STEP 5:
         * Verify the authentication session.
         *
         * This prevents a revoked or expired session from
         * continuing to access protected endpoints.
         */
        const session = await findActiveSessionBySessionId(
            decoded.sid
        );

        if (!session) {
            throw createAuthenticationError(
                "Authentication session is invalid, revoked, or expired."
            );
        }


        /**
         * STEP 6:
         * Ensure the token subject matches the session owner.
         *
         * Never trust a user ID merely because it exists in a JWT.
         */
        if (session.user_id !== decoded.sub) {
            throw createAuthenticationError(
                "Access token does not match the authentication session."
            );
        }


        /**
         * STEP 7:
         * Load the current user record.
         *
         * This check allows account deactivation and login disabling
         * to take effect without waiting for the access token to expire.
         */
        const user = await findUserById(decoded.sub);

        if (!user) {
            throw createAuthenticationError(
                "Authenticated user was not found."
            );
        }

        if (!user.is_active) {
            throw createAuthenticationError(
                "User account is inactive."
            );
        }

        if (!user.is_login_enabled) {
            throw createAuthenticationError(
                "Login is disabled for this account."
            );
        }


        /**
         * STEP 8:
         * Attach only the required verified user information.
         *
         * Password hashes and other authentication secrets must
         * never be exposed through req.user.
         */
        req.user = {
            id: user.id,
            email: user.email,
            phone: user.phone,
            firstName: user.first_name,
            middleName: user.middle_name,
            lastName: user.last_name,
            sessionId: session.session_id,
        };


        /**
         * STEP 9:
         * Continue to the protected route.
         */
        return next();

    } catch (error) {
        return next(error);
    }
};